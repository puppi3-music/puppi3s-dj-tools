"""Build docs/commands/search-index.js, the data behind the command reference's search box.

The search runs in the browser, also from a page opened straight from disk (file://), where a page
may not fetch its neighbours; so the index ships as a script that sets window.REF_INDEX.

Entries: every area page, every <h2>/<h3 id> section (commands, "Before you start", ...) and every
row of each page's "All options" table.

    uv run python .claude/skills/update-docs/scripts/ref_index.py           # rewrite the index
    uv run python .claude/skills/update-docs/scripts/ref_index.py --check   # exit 1 if it's stale
"""
import html
import json
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parents[4] / "docs" / "commands"
OUT = DOCS / "search-index.js"
# Overview first, then the areas in the order of the reference's own contents
ORDER = ["index", "colours", "library", "genres", "hype-sets", "cues-grids-sync", "tempo", "mixes", "app"]
SKIP = {"all-options", "areas"}  # the options table is indexed row by row; "areas" is the list of pages


def text(fragment: str) -> str:
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", fragment)).split())


def first_sentence(fragment: str, limit: int = 150) -> str:
    t = text(fragment)
    m = re.match(r"(.+?[.!?])(\s|$)", t)
    t = m.group(1) if m else t
    return t if len(t) <= limit else t[: limit - 1].rsplit(" ", 1)[0] + "…"


def page_entries(name: str) -> list[dict]:
    src = (DOCS / f"{name}.html").read_text()
    h1 = text(re.search(r"<h1[^>]*>(.*?)</h1>", src, re.S).group(1))
    area = "Overview" if name == "index" else h1
    lede = re.search(r"<h1.*?</h1>\s*<p[^>]*>(.*?)</p>", src, re.S)
    out = [{"k": "area", "t": h1, "a": "Command reference" if name != "index" else "",
            "d": first_sentence(lede.group(1)) if lede else "", "u": f"{name}.html"}]
    for m in re.finditer(r'<h([23]) id="([^"]+)"[^>]*>(.*?)</h\1>(.*?)(?=<h[23][ >]|<script|$)', src, re.S):
        level, sid, title, body = m.groups()
        if sid in SKIP:
            continue
        p = re.search(r"<p[^>]*>(.*?)</p>", body, re.S)
        is_cmd = title.strip().startswith("<code>")
        out.append({"k": "cmd" if is_cmd else "sec", "t": text(title), "a": area,
                    "d": first_sentence(p.group(1)) if p else "", "u": f"{name}.html#{sid}"})
    table = re.search(r'<table id="opt-table">(.*?)</table>', src, re.S)
    for row in re.findall(r"<tr>(.*?)</tr>", table.group(1) if table else "", re.S):
        cells = re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)
        if len(cells) < 2:
            continue
        opt = text(cells[0])
        d = "With " + text(cells[1]) + (f" · default {text(cells[2])}" if len(cells) > 2 and text(cells[2]) else "")
        flag = opt.split()[0]
        out.append({"k": "opt", "t": opt, "a": area, "d": d,
                    "u": f"{name}.html?opt={flag}#all-options"})
    return out


def build() -> str:
    missing = sorted({p.stem for p in DOCS.glob("*.html")} - set(ORDER))
    if missing:
        sys.exit(f"ref_index.py: add {missing} to ORDER")
    entries = [e for name in ORDER for e in page_entries(name)]
    lines = ",\n".join(json.dumps(e, ensure_ascii=False) for e in entries)
    return ("// Generated by .claude/skills/update-docs/scripts/ref_index.py from the pages in this folder.\n"
            "// Don't edit by hand: rerun the script after changing a page.\n"
            f"window.REF_INDEX = [\n{lines}\n];\n")


if __name__ == "__main__":
    new = build()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != new
        print("search index:", "STALE, rerun ref_index.py" if stale else "up to date")
        sys.exit(1 if stale else 0)
    OUT.write_text(new)
    print(f"wrote {OUT.relative_to(DOCS.parents[1])}: {new.count(chr(10)) - 3} entries")
