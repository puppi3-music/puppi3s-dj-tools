"""Tables for src/musicnn.rs, read off Essentia and this Mac's libm (run on macOS, in the analyzer's environment):

    uv run python dsp/tools/gen_musicnn_tables.py dsp/src/musicnn_tables.rs

- WINDOW: Essentia's Windowing(hann, normalized=False, zeroPhase=True) of 512 ones, i.e. the window as applied.
- MEL_*: MelBands as TensorflowInputMusiCNN configures it (96 Slaney bands, 0-8 kHz, unit_tri), read band by band
  from one-hot spectra (1 * 1 * weight + 0 is exact), stored sparse: first bin and weights of each band.
- TW512: FFTW 3.3.10's twiddles for its 512-point r2c plan (hc2cf_32: TW_FULL 1..31, m = 1..7). FFTW_SINGLE plans
  use the sqrt(n) table (AWAKE_SQRTN_TABLE): cexp(m) = W1[m >> 5] * W0[m & 31] in double, entries from real_cexp
  (octant reduction, libm cos/sin), products fused as gcc fuses them, then rounded to float.
- LOG10F_FIX: (x, log10f(x)) wherever (float)log10((double)x) isn't safely macOS's log10f, which isn't correctly
  rounded (log10f_exceptions.c).
"""
import math
import struct
import subprocess
import sys
import tempfile
from fractions import Fraction
from pathlib import Path

import numpy as np

from dj_track_analyzer import analysis as a

HERE = Path(__file__).resolve().parent
K2PI = 6.2831853071795864769252867665590057683943388


def bits(x) -> int:
    return struct.unpack("<I", struct.pack("<f", float(x)))[0]


def real_cexp(m, n):  # FFTW kernel/trig.c
    octant, quarter_n = 0, n
    n *= 4
    m *= 4
    if m < 0:
        m += n
    if m > n - m:
        m, octant = n - m, octant | 4
    if m - quarter_n > 0:
        m, octant = m - quarter_n, octant | 2
    if m > quarter_n - m:
        m, octant = quarter_n - m, octant | 1
    theta = (K2PI * m) / n
    c, s = math.cos(theta), math.sin(theta)
    if octant & 1:
        c, s = s, c
    if octant & 2:
        c, s = -s, c
    if octant & 4:
        s = -s
    return c, s


def fma(x, y, z):  # exact, then one rounding to double
    return float(Fraction(x) * Fraction(y) + Fraction(z))


def twiddles():
    n, shift = 512, 5  # choose_twshft(512) = 5
    W0 = [real_cexp(i, n) for i in range(1 << shift)]
    W1 = [real_cexp(i << shift, n) for i in range((n + (1 << shift) - 1) >> shift)]
    out = []
    for j in range(7):
        for i in range(1, 32):
            m = (j + 1) * i
            wr0, wi0 = W0[m & 31]
            wr1, wi1 = W1[m >> shift]
            out += [bits(fma(wr1, wr0, -(wi1 * wi0))), bits(fma(wi1, wr0, wr1 * wi0))]
    return out


def log10f_fix():
    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "log10f_exceptions"
        subprocess.run(["clang", "-O2", "-ffp-contract=off", "-o", str(exe), str(HERE / "log10f_exceptions.c")], check=True)
        lines = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout.split()
    return sorted({(int(lines[i], 16), int(lines[i + 1], 16)) for i in range(0, len(lines), 2)})


def table(name, vals, ty="u32", per=8):
    rows = [", ".join(f"0x{v:08x}" for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"pub static {name}: [{ty}; {len(vals)}] = [\n" + "".join(f"    {r},\n" for r in rows) + "];\n"


def main():
    if sys.platform != "darwin":
        raise SystemExit("run this on macOS: the tables follow Essentia's macOS build and macOS's libm")
    e = a.es()
    win = np.asarray(e.Windowing(type="hann", normalized=False, size=512)(np.ones(512, np.float32)), np.float32)
    mb = e.MelBands(inputSize=257, numberBands=96, sampleRate=16000, highFrequencyBound=8000,
                    warpingFormula="slaneyMel", weighting="linear", normalize="unit_tri")
    F = np.zeros((96, 257), np.float32)
    for j in range(257):
        s = np.zeros(257, np.float32)
        s[j] = 1
        F[:, j] = mb(s)
    starts, lens, weights = [], [], []
    for b in range(96):
        nz = np.flatnonzero(F[b])
        lo, hi = int(nz[0]), int(nz[-1])
        assert (F[b, lo:hi + 1] != 0).all()  # contiguous: the zeros outside add nothing in Essentia's loop
        starts.append(lo)
        lens.append(hi - lo + 1)
        weights += [bits(v) for v in F[b, lo:hi + 1]]
    fix = log10f_fix()
    out = ["// Generated by dsp/tools/gen_musicnn_tables.py from Essentia (AGPL-3.0) and FFTW 3.3.10 (GPL-2.0-or-later)",
           "// on macOS. Do not edit by hand.", "",
           table("WINDOW", [bits(v) for v in win]),
           "pub static MEL_START: [u16; 96] = [" + ", ".join(map(str, starts)) + "];\n",
           "pub static MEL_LEN: [u16; 96] = [" + ", ".join(map(str, lens)) + "];\n",
           table("MEL_WEIGHTS", weights),
           table("TW512", twiddles()),
           f"pub static LOG10F_FIX: [(u32, u32); {len(fix)}] = [\n"
           + "".join(f"    (0x{x:08x}, 0x{y:08x}),\n" for x, y in fix) + "];\n"]
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"wrote {sys.argv[1]}: {len(weights)} mel weights, {len(fix)} log10f fixes")


if __name__ == "__main__":
    main()
