"""Tables for src/fftw.rs and src/bpm.rs, read off Essentia and FFTW's maths on macOS (run in the analyzer's environment):

    uv run python dsp/tools/gen_bpm_tables.py dsp/src/bpm_tables.rs

- TRIG_*: the entries of FFTW 3.3.10's sqrt(n) trig tables (kernel/trig.c, real_cexp: octant reduction, libm cos and
  sin in double), from which src/fftw.rs makes the twiddles of every plan up to 2^22 points. real_cexp(i, n) depends
  only on i/n (scaling i and n by 2 scales m and n alike: the same doubles), so each entry is stored once, under
  k = i * 2^22 / n: W0 (i < 2^shift) and W1 (i << shift) of every n = 2^1 .. 2^22.
- HANN2048: Windowing(hann, size 2048, normalized) of 2048 ones with zeroPhase off: the window BeatTrackerMultiFeature and
  OnsetDetectionGlobal use.
- MEL40_*: OnsetDetection's MelBands (40 bands, 0-4000 Hz, htkMel, unit_sum, power) on 1025 bins, read band by band from
  one-hot spectra (1 * 1 * weight + 0 is exact), stored sparse: first bin, length, weights.
- ERB40: OnsetDetectionGlobal's ERBBands (40 bands, 80-22050 Hz, magnitude) on 1025 bins, the same way, dense.
- RAYLEIGH512, GAUSS_VITERBI, GAUSS_IBI1/2: the weights bpm.rs would compute with exp in double (Python's):
  beat_emphasis' and createTempoPreferenceCurve's Rayleigh weighting (both rayparam 43, the latter
  the first 128), and TempoTapDegara's gaussianPDFs (the Viterbi matrix's; the beat tracker's, resample 1 and 2).
"""
import math
import struct
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_musicnn_tables import bits, choose_twshft, real_cexp, table  # noqa: E402

from dj_track_analyzer import analysis as a  # noqa: E402


def one_hot(alg, bands, size=1025):
    out = np.zeros((bands, size), np.float32)
    for j in range(size):
        s = np.zeros(size, np.float32)
        s[j] = 1
        out[:, j] = alg(s)
    return out


TRIG_P = 22


def trig_entries():
    ks = set()
    for p in range(1, TRIG_P + 1):
        n, shift = 1 << p, choose_twshft(1 << p)
        scale = 1 << (TRIG_P - p)
        ks.update(i * scale for i in range(1 << shift))
        ks.update((i << shift) * scale for i in range((n + (1 << shift) - 1) >> shift))
    out = sorted(ks)
    for p in range(1, TRIG_P + 1):  # the claim above, checked
        scale = 1 << (TRIG_P - p)
        for i in range(0, 1 << p, max(1, (1 << p) // 4096)):
            assert real_cexp(i, 1 << p) == real_cexp(i * scale, 1 << TRIG_P)
    return out


F = np.float32


def rayleigh(n):
    """bpm.rs's Rayleigh weights for tau = 1..n: (tau / rayparam2) in float, times exp(-0.5 tau^2 / rayparam2) in double."""
    rp2 = F(43.0 * 43.0)  # pow(round(60 * 86.1328125 / 120), 2)
    return [bits(F(float(F(tau) / rp2) * math.exp(-0.5 * tau * tau / float(rp2)))) for tau in range(1, n + 1)]


def gaussian(std, step, scale):
    """TempoTapDegara::gaussianPDF as bpm.rs would compute it."""
    std, step, scale = F(std), F(step), F(scale)
    size = int(F(2.0) * np.ceil(F(4.0) * std / step) + F(1.0))
    mean = size // 2
    term1 = F(1.0 / (float(std) * math.sqrt(2.0 * math.pi)))
    term2 = F(-2.0 * (float(std) * float(std)))
    g = [0] * size
    for i in range(mean + 1):
        d = F(F(i - mean) * step)
        v = F(float(term1) * math.exp(float(d) * float(d) / float(term2)) * float(scale))
        g[i] = g[size - 1 - i] = 0 if v < F(1e-12) else bits(v)
    return g


def f64_table(name, vals, per=4):
    rows = [", ".join(f"0x{struct.unpack('<Q', struct.pack('<d', v))[0]:016x}" for v in vals[i:i + per])
            for i in range(0, len(vals), per)]
    return f"pub static {name}: [u64; {len(vals)}] = [\n" + "".join(f"    {r},\n" for r in rows) + "];\n"


def main():
    if sys.platform != "darwin":
        raise SystemExit("run this on macOS: the tables follow Essentia's macOS build and macOS's libm")
    out = ["// Generated by dsp/tools/gen_bpm_tables.py from Essentia (AGPL-3.0) and FFTW 3.3.10 (GPL-2.0-or-later)",
           "// on macOS. Do not edit by hand.", "",
           f"pub const TRIG_P: u32 = {TRIG_P};\n"]
    ks = trig_entries()
    cs = [real_cexp(k, 1 << TRIG_P) for k in ks]
    out += [table("TRIG_K", ks), f64_table("TRIG_C", [c for c, _ in cs]), f64_table("TRIG_S", [s for _, s in cs])]
    e = a.es()
    w = np.asarray(e.Windowing(type="hann", size=2048, zeroPhase=False)(np.ones(2048, np.float32)), np.float32)
    out.append(table("HANN2048", [bits(v) for v in w]))
    mel = one_hot(e.MelBands(inputSize=1025, sampleRate=44100, numberBands=40, lowFrequencyBound=0.0,
                             highFrequencyBound=4000.0), 40)
    starts, lens, weights = [], [], []
    for b in range(40):
        nz = np.flatnonzero(mel[b])
        lo, hi = int(nz[0]), int(nz[-1])
        assert (mel[b, lo:hi + 1] != 0).all()  # contiguous: the zeros outside add nothing in Essentia's loop
        starts.append(lo)
        lens.append(hi - lo + 1)
        weights += [bits(v) for v in mel[b, lo:hi + 1]]
    out += ["pub static MEL40_START: [u16; 40] = [" + ", ".join(map(str, starts)) + "];\n",
            "pub static MEL40_LEN: [u16; 40] = [" + ", ".join(map(str, lens)) + "];\n",
            table("MEL40_WEIGHTS", weights)]
    erb = one_hot(e.ERBBands(inputSize=1025, numberBands=40, lowFrequencyBound=80.0, highFrequencyBound=22050.0,
                             sampleRate=44100, type="magnitude"), 40)
    out.append(table("ERB40", [bits(v) for v in erb.reshape(-1)]))
    sr = F(44100.0 / 512.0)
    out += [table("RAYLEIGH512", rayleigh(512)), table("GAUSS_VITERBI", gaussian(8.0, 1.0, 1.0)),
            table("GAUSS_IBI1", gaussian(0.025, F(1.0 / float(sr)), F(0.01 / 1))),
            table("GAUSS_IBI2", gaussian(0.025, F(1.0 / float(sr)), F(0.01 / 2)))]
    rs = Path(sys.argv[1])
    rs.write_text("\n".join(out))
    print(f"wrote {rs}")


if __name__ == "__main__":
    main()
