"""Tables for src/key.rs, read off Essentia on macOS (run in the analyzer's environment):

    uv run python dsp/tools/gen_key_tables.py dsp/src/key_tables.rs

- HANN4096: Essentia's Windowing(hann, size 4096, normalized=True), as KeyExtractor configures it, of 4096 ones with
  zeroPhase off: the window itself, w[0..4096].
- TW4096: FFTW 3.3.10's twiddles for its 4096-point r2c plan (hc2cf_32, m = 1..63), made as TW512 is
  (gen_musicnn_tables.py).
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_musicnn_tables import bits, table, twiddles  # noqa: E402

from dj_track_analyzer import analysis as a  # noqa: E402


def main():
    if sys.platform != "darwin":
        raise SystemExit("run this on macOS: the tables follow Essentia's macOS build")
    w = np.asarray(a.es().Windowing(type="hann", size=4096, zeroPhase=False)(np.ones(4096, np.float32)), np.float32)
    out = ["// Generated by dsp/tools/gen_key_tables.py from Essentia (AGPL-3.0) and FFTW 3.3.10 (GPL-2.0-or-later)",
           "// on macOS. Do not edit by hand.", "",
           table("HANN4096", [bits(v) for v in w]),
           table("TW4096", twiddles(4096))]
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"wrote {sys.argv[1]}")


if __name__ == "__main__":
    main()
